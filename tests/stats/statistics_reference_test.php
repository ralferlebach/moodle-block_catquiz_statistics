 * Statistics validated against R reference results (Issue #8).
 *
 * Fixtures: tests/fixtures/stats/data.csv and reference.csv, generated by
 * tests/fixtures/stats/reference.R (R >= 4.3, base packages). Tolerance:
 * 1e-9 relative to max(1, |reference|).
